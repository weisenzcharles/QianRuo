package com.ruoyi.merchant.model;

import java.util.Arrays;
import java.util.Set;
import java.util.stream.Collectors;
import org.junit.Test;

/** 公开商户申请不能接受服务端归属和审核字段。 */
public class MerchantRegistrationContractTest
{
    /**
     * 验证公开注册命令不暴露租户、商户唯一编号、审核状态和商户状态等服务端字段。
     */
    @Test
    public void publicCommandDoesNotExposeServerOwnedFields()
    {
        Set<String> fields = Arrays.stream(MerchantRegistrationCommand.class.getDeclaredFields())
                .map(field -> field.getName())
                .collect(Collectors.toSet());

        require(!fields.contains("tenantId"), "tenantId must not be exposed");
        require(!fields.contains("merchantId"), "merchantId must not be exposed");
        require(!fields.contains("authStatus"), "authStatus must not be exposed");
        require(!fields.contains("status"), "merchant status must not be exposed");
        require(!fields.contains("memberCode"), "memberCode must be generated by the platform");
        require(fields.contains("legalIdFrontUrl"), "identity-card front image must be exposed for registration");
        require(fields.contains("legalIdBackUrl"), "identity-card back image must be exposed for registration");
    }

    /**
     * 执行无第三方依赖的测试断言。
     *
     * @param condition 期望成立的条件
     * @param message 断言失败提示
     */
    private void require(boolean condition, String message)
    {
        if (!condition)
        {
            throw new AssertionError(message);
        }
    }
}

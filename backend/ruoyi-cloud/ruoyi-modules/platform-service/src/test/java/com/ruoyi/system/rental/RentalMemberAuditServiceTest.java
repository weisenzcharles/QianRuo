package com.ruoyi.system.rental;

import java.lang.reflect.Field;
import java.lang.reflect.Proxy;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.Test;
import com.ruoyi.common.core.domain.R;
import com.ruoyi.common.core.exception.ServiceException;
import com.ruoyi.merchant.api.RemoteMerchantUserService;
import com.ruoyi.merchant.api.model.MerchantOwnerProvisionCommand;
import com.ruoyi.system.domain.rental.RentalMember;
import com.ruoyi.system.mapper.rental.RentalMemberMapper;
import com.ruoyi.system.model.rental.RentalMemberAuditCommand;
import com.ruoyi.system.service.rental.RentalMemberLifecyclePolicy;
import com.ruoyi.system.service.rental.impl.RentalMemberServiceImpl;

/** 商户审核必须通过独立状态机并开通商户侧管理员。 */
public class RentalMemberAuditServiceTest
{
    /**
     * 验证待审核申请通过后会原子更新审核状态，并向商户服务发送可信所有者开户命令。
     */
    @Test
    public void approvedApplicationProvisionsMerchantOwner() throws Exception
    {
        AtomicReference<RentalMember> updated = new AtomicReference<RentalMember>();
        AtomicReference<MerchantOwnerProvisionCommand> provisioned = new AtomicReference<MerchantOwnerProvisionCommand>();
        RentalMemberServiceImpl service = service(updated, provisioned);

        RentalMemberAuditCommand command = new RentalMemberAuditCommand();
        command.setAuthStatus("verified");
        command.setAuditRemark("资料完整");

        int rows = service.auditRentalMember(10L, command, "platform-admin");

        require(rows == 1, "audit should update one member");
        require("verified".equals(updated.get().getAuthStatus()), "member should become verified");
        require(updated.get().getAuditTime() != null, "audit time should be generated by the server");
        require(provisioned.get() != null, "merchant owner should be provisioned");
        require(Long.valueOf(10L).equals(provisioned.get().getMerchantId()), "merchant id must come from the server");
        require("15500000000".equals(provisioned.get().getPhone()), "owner phone should use the application phone");
    }

    /**
     * 验证审核驳回必须填写具体原因，防止商户无法判断需要修改的资料。
     */
    @Test(expected = ServiceException.class)
    public void rejectedApplicationRequiresReason() throws Exception
    {
        RentalMemberServiceImpl service = service(new AtomicReference<RentalMember>(),
                new AtomicReference<MerchantOwnerProvisionCommand>());
        RentalMemberAuditCommand command = new RentalMemberAuditCommand();
        command.setAuthStatus("rejected");
        command.setAuditRemark(" ");
        service.auditRentalMember(10L, command, "platform-admin");
    }

    /**
     * 创建使用动态代理隔离数据库和远程服务的被测服务实例。
     *
     * @param updated 接收数据库审核更新记录的引用
     * @param provisioned 接收远程开户命令的引用
     * @return 已注入测试依赖的商户服务实现
     */
    private RentalMemberServiceImpl service(AtomicReference<RentalMember> updated,
            AtomicReference<MerchantOwnerProvisionCommand> provisioned) throws Exception
    {
        RentalMemberMapper mapper = (RentalMemberMapper) Proxy.newProxyInstance(getClass().getClassLoader(),
                new Class<?>[] { RentalMemberMapper.class }, (proxy, method, args) -> {
                    if ("selectRentalMemberById".equals(method.getName()))
                    {
                        return pendingMember();
                    }
                    if ("auditRentalMember".equals(method.getName()))
                    {
                        updated.set((RentalMember) args[0]);
                        return 1;
                    }
                    return null;
                });
        RemoteMerchantUserService remote = (RemoteMerchantUserService) Proxy.newProxyInstance(
                getClass().getClassLoader(), new Class<?>[] { RemoteMerchantUserService.class },
                (proxy, method, args) -> {
                    if ("provisionOwner".equals(method.getName()))
                    {
                        provisioned.set((MerchantOwnerProvisionCommand) args[0]);
                        return R.ok(Boolean.TRUE);
                    }
                    return null;
                });

        RentalMemberServiceImpl service = new RentalMemberServiceImpl();
        inject(service, "memberMapper", mapper);
        inject(service, "lifecyclePolicy", new RentalMemberLifecyclePolicy());
        inject(service, "remoteMerchantUserService", remote);
        return service;
    }

    /**
     * 构造字段完整的待审核商户申请，供审核状态机测试使用。
     *
     * @return 待审核商户实体
     */
    private RentalMember pendingMember()
    {
        RentalMember member = new RentalMember();
        member.setMemberId(10L);
        member.setTenantId(1L);
        member.setMemberCode("M202607240001");
        member.setMemberType("personal");
        member.setAuthStatus("pending");
        member.setNickname("测试店铺");
        member.setContactName("张三");
        member.setContactPhone("15500000000");
        member.setVipLevel("free");
        member.setStorageQuotaMb(1024L);
        member.setExternalAcceptEnabled(0);
        member.setLicenseLongTerm(0);
        member.setStatus("0");
        return member;
    }

    /**
     * 通过反射注入测试替身，避免启动完整 Spring 容器。
     *
     * @param target 待注入对象
     * @param fieldName 目标字段名称
     * @param value 测试替身
     */
    private void inject(Object target, String fieldName, Object value) throws Exception
    {
        Field field = target.getClass().getDeclaredField(fieldName);
        field.setAccessible(true);
        field.set(target, value);
    }

    /**
     * 执行无第三方依赖的测试断言。
     *
     * @param condition 期望成立的条件
     * @param message 断言失败提示
     */
    private void require(boolean condition, String message)
    {
        if (!condition)
        {
            throw new AssertionError(message);
        }
    }
}
